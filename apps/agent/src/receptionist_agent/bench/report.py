"""Benchmark report: P50/P95 per stage per config, from data/bench/results/*.jsonl."""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from collections.abc import Mapping
from datetime import date
from pathlib import Path
from typing import Any

STAGES = [
    ("first_audio_ms", "caller stops -> first agent audio"),
    ("vad_stop_ms", "VAD notices silence"),
    ("stt_final_ms", "final transcript"),
    ("turn_released_ms", "end of turn (LLM may start)"),
    ("llm_first_token_ms", "LLM first text"),
    ("tts_first_audio_ms", "TTS first audio"),
]


def percentile(values: list[float], pct: float) -> float | None:
    """Nearest-rank percentile; None for no data."""
    if not values:
        return None
    ordered = sorted(values)
    rank = max(1, -(-len(ordered) * pct // 100))
    return ordered[int(rank) - 1]


def latest_results(results_dir: Path) -> dict[str, list[dict[str, Any]]]:
    """Rows of the newest results file for each config name."""
    newest: dict[str, Path] = {}
    for path in sorted(results_dir.glob("*.jsonl")):
        config = path.stem.split("-", 2)[-1]
        newest[config] = path  # sorted by timestamp prefix, so the last one wins
    return {
        config: [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
        for config, path in newest.items()
    }


def _fmt(v: float | None) -> str:
    return "-" if v is None else f"{v:,.0f}"


DURATIONS = [
    ("vad", "VAD notices silence", None, "vad_stop_ms"),
    ("stt", "STT after VAD", "vad_stop_ms", "stt_final_ms"),
    ("eot", "end of turn after STT", "stt_final_ms", "turn_released_ms"),
    ("llm", "LLM first text after end of turn", "turn_released_ms", "llm_first_token_ms"),
    ("tts", "TTS first audio after LLM text", "llm_first_token_ms", "tts_first_audio_ms"),
]


def stage_durations(r: dict[str, Any]) -> dict[str, float]:
    """How long each stage took in one turn (only stages that ran in order)."""
    out: dict[str, float] = {}
    for key, _label, start, end in DURATIONS:
        b = r.get(end)
        a = 0.0 if start is None else r.get(start)
        if isinstance(a, int | float) and isinstance(b, int | float) and b >= a:
            out[key] = b - a
    return out


def answered_by(r: dict[str, Any]) -> str | None:
    """The model behind a turn, if one model answered all of its requests."""
    targets = set(r.get("llm_targets") or [])
    return targets.pop() if len(targets) == 1 else None


def summarize(rows: list[dict[str, Any]]) -> dict[str, Any]:
    turns = [r for r in rows if r["type"] == "turn"]
    out: dict[str, Any] = {"n": len(turns), "timeouts": sum(r["timed_out"] for r in turns)}
    durations = [stage_durations(r) for r in turns]
    out["durations"] = {
        key: percentile([d[key] for d in durations if key in d], 50) for key, *_ in DURATIONS
    }
    groq = [
        r["first_audio_ms"]
        for r in turns
        if r.get("first_audio_ms") is not None and (answered_by(r) or "").startswith("groq:")
    ]
    out["groq_first_audio"] = (percentile(groq, 50), len(groq))
    for key, _ in STAGES:
        values = [r[key] for r in turns if r.get(key) is not None]
        out[key] = (percentile(values, 50), percentile(values, 95))
    by_kind: dict[str, list[float]] = defaultdict(list)
    for r in turns:
        if r.get("first_audio_ms") is not None:
            by_kind[r["kind"]].append(r["first_audio_ms"])
    out["by_kind"] = {k: (percentile(v, 50), len(v)) for k, v in sorted(by_kind.items())}
    served = Counter(t for r in turns for t in r.get("llm_targets", []))
    out["llm"] = dict(served.most_common())
    out["under_1s"] = sum(
        1 for r in turns if r.get("first_audio_ms") is not None and r["first_audio_ms"] < 1000
    )
    out["barge_in"] = [r for r in rows if r["type"] == "barge_in"]
    return out


def render(results: Mapping[str, list[dict[str, Any]]], configs: Mapping[str, Any]) -> str:
    names = [n for n in configs if n in results] + [n for n in results if n not in configs]
    summaries = {n: summarize(results[n]) for n in names}
    lines = [
        f"# Latency benchmark, {date.today():%Y-%m-%d}",
        "",
        "Generated by `make bench` (apps/agent/src/receptionist_agent/bench). 20 caller utterances",
        "(10 English, 10 Urdu, synthetic voices) through the real pipeline on this laptop's CPU:",
        "Silero VAD, Smart Turn v3, Groq Whisper STT, the LLM with its free-tier fallback,",
        "local TTS.",
        "Time zero is when the caller's audio really ended; the network is not included.",
        "",
        "## Caller stops speaking -> first agent audio (ms)",
        "",
        "| config | P50 | P95 | under 1 s | P50, Groq-answered turns (n) | turns | timeouts |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for n in names:
        s = summaries[n]
        p50, p95 = s["first_audio_ms"]
        under = f"{s['under_1s']}/{s['n']}"
        g50, gn = s["groq_first_audio"]
        lines.append(
            f"| {n} | {_fmt(p50)} | {_fmt(p95)} | {under} | {_fmt(g50)} ({gn}) | {s['n']} "
            f"| {s['timeouts']} |"
        )
    lines += [
        "",
        "## How long each stage took: P50 per turn (ms)",
        "",
        "Each stage is timed on its own, so configs compare fairly even when a different LLM",
        "answered: TTS changes show in the last column, VAD changes in the first.",
        "",
        "| config | " + " | ".join(label for _, label, *_ in DURATIONS) + " |",
        "|---|" + "---:|" * len(DURATIONS),
    ]
    for n in names:
        d = summaries[n]["durations"]
        lines.append(f"| {n} | " + " | ".join(_fmt(d[k]) for k, *_ in DURATIONS) + " |")
    by_model: dict[str, list[float]] = defaultdict(list)
    by_model_audio: dict[str, list[float]] = defaultdict(list)
    for n in names:
        if configs.get(n, {}).get("tts_provider") == "kokoro":
            continue  # Kokoro's slowness would blur the comparison
        for r in results[n]:
            model = answered_by(r) if r["type"] == "turn" else None
            if model is None:
                continue
            if "llm" in (d := stage_durations(r)):
                by_model[model].append(d["llm"])
            if r.get("first_audio_ms") is not None:
                by_model_audio[model].append(r["first_audio_ms"])
    lines += [
        "",
        "## By the LLM that answered (all non-Kokoro configs)",
        "",
        "| model | LLM first text after end of turn, P50 | first audio, P50 | P95 | turns |",
        "|---|---:|---:|---:|---:|",
    ]
    for model in sorted(by_model_audio, key=lambda m: -len(by_model_audio[m])):
        audio = by_model_audio[model]
        lines.append(
            f"| {model} | {_fmt(percentile(by_model[model], 50))} | "
            f"{_fmt(percentile(audio, 50))} | {_fmt(percentile(audio, 95))} | {len(audio)} |"
        )
    lines += ["", "## Where the time goes: P50 offsets from caller stop (ms)", ""]
    lines.append("| config | " + " | ".join(label for _, label in STAGES[1:]) + " |")
    lines.append("|---|" + "---:|" * (len(STAGES) - 1))
    for n in names:
        s = summaries[n]
        lines.append(f"| {n} | " + " | ".join(_fmt(s[k][0]) for k, _ in STAGES[1:]) + " |")
    lines += ["", "## P50 first audio by turn type (ms, n)", ""]
    kinds = sorted({k for s in summaries.values() for k in s["by_kind"]})
    lines.append("| config | " + " | ".join(kinds) + " |")
    lines.append("|---|" + "---:|" * len(kinds))
    for n in names:
        bk = summaries[n]["by_kind"]
        cells = [f"{_fmt(bk[k][0])} ({bk[k][1]})" if k in bk else "-" for k in kinds]
        lines.append(f"| {n} | " + " | ".join(cells) + " |")
    lines += ["", "## Which LLM answered (requests)", ""]
    for n in names:
        mix = ", ".join(f"{k} {v}" for k, v in summaries[n]["llm"].items()) or "-"
        lines.append(f"- **{n}:** {mix}")
    lines += [
        "",
        "## Barge-in (caller talks over the agent)",
        "",
        "Times from the moment the caller starts talking over the agent (ms).",
        "",
        "| config | agent was speaking | VAD notices | reply interrupted | audio stops "
        "| stop after interruption | leaked chunks | kept / written chars "
        "| kept = start of reply |",
        "|---|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for n in names:
        for b in summaries[n]["barge_in"]:
            lines.append(
                f"| {n} | {'yes' if b['agent_was_speaking'] else 'no'} "
                f"| {_fmt(b['vad_detect_ms'])} | {_fmt(b['interruption_ms'])} "
                f"| {_fmt(b['audio_stop_ms'])} | {_fmt(b['stop_after_interruption_ms'])} "
                f"| {b['leaked_chunks']} | {b['kept_chars']} / {b['generated_chars']} "
                f"| {'yes' if b['kept_is_prefix'] else 'no'} |"
            )
    lines += ["", "## Configs", ""]
    for n in names:
        lines.append(f"- **{n}:** `{json.dumps(configs.get(n, {}))}`")
    return "\n".join(lines) + "\n"


def write_report(results_dir: Path, out_dir: Path, *, configs: Mapping[str, Any]) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{date.today():%Y-%m-%d}.md"
    path.write_text(render(latest_results(results_dir), configs))
    return path
